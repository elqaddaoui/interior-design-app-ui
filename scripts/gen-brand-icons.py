def path(name):
    if name not in glyph_map: return None
    g = cmap.get(glyph_map[name])
    if not g: return None
    pen = SVGPathPen(gs, ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
    # y flips: svg_y = (448 - y) * K  (ascent 448); x * K
    tp = TransformPen(pen, (K, 0, 0, -K, 0, 448 * K))
    gs[g].draw(tp)
    return pen.getCommands()

missing = []
rows = []
seen = set()
for cat, names in LOGO.items():
    for n in names:
        if n in seen: continue
        seen.add(n)
        d = path(n)
        if d: rows.append(f"{cat}|{n}|{d}")
        else: missing.append(n)

with open(f'{ROOT}/src/lib/brand/iconPaths.ts', 'w') as f:
    f.write("/* Generated by scripts/gen-brand-icons.py from the MaterialCommunityIcons font - do not edit by hand. 24x24 grid.\n")
    f.write(" * One \"group|name|pathData\" string per icon, so the glyph names are not picked up by scripts/subset-icons.py\n")
    f.write(" * (the web icon font stays small: these icons are drawn as SVG paths, never from the font). */\n")
    f.write("export const ICON_DATA: string[] = [\n" + "\n".join("  " + json.dumps(r) + "," for r in rows) + "\n];\n")
print(f'logo icons: {len(rows)}')
if missing: print('MISSING:', ', '.join(sorted(set(missing))))
