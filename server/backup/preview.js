/**
 * The preview of a backup: a small picture of how the app looked when the backup was made.
 *
 * The browser takes a real screenshot of the app just before the backup starts (src/superadmin/screenshot.web.ts) and hands it over
 * (POST /backup/previews). When that is not possible (no browser, a blocked frame, a scheduled backup at night) the server builds a
 * snapshot of the same thing from the data itself: the store name, its colours and what it holds. It is an SVG made only of text and
 * shapes (no external resource, every value escaped) and it is only ever shown inside an <img>, never inlined in a page.
 */
const esc = value => String(value ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c]));
const color = (value, fallback) => (/^#[0-9a-f]{3,8}$/i.test(String(value || '')) ? String(value) : fallback);
const count = async (db, sql, params = []) => { try { return Number((await db.query(sql, params))[0]?.n) || 0; } catch { return 0; } };
const PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const JPG = Buffer.from([0xff, 0xd8, 0xff]);

/** 'image/png' | 'image/jpeg' for real picture bytes, else null: the browser's screenshot is only accepted when its bytes say so. */
function imageType(buffer) {
  if (buffer.length > 8 && buffer.subarray(0, 8).equals(PNG)) return 'image/png';
  if (buffer.length > 3 && buffer.subarray(0, 3).equals(JPG)) return 'image/jpeg';
  return null;
}

async function buildPreview({ db, version, at, kind }) {
  const doc = async name => { try { return JSON.parse((await db.query("SELECT data FROM content_docs WHERE tenant_id='default' AND name=$1", [name]))[0]?.data || '{}'); } catch { return {}; } };
  const branding = await doc('branding');
  const theme = await doc('theme');
  const custom = theme?.custom && typeof theme.custom === 'object' ? theme.custom : {};
  const accent = color(custom.primary || custom.accent, '#4F46E5');
  const dark = /dark|night/i.test(String(theme?.active || ''));
  const bg = dark ? '#12141c' : '#f6f7fb', fg = dark ? '#f2f3f8' : '#161a2b', muted = dark ? '#9aa1b8' : '#5b6480';
  const name = esc(String(branding?.appName || 'App').slice(0, 28));
  const [tools, styles, clients, requests, media] = await Promise.all([
    count(db, "SELECT COUNT(*) AS n FROM content_items WHERE tenant_id='default' AND coll='tools'"),
    count(db, "SELECT COUNT(*) AS n FROM content_items WHERE tenant_id='default' AND coll='styles'"),
    count(db, "SELECT COUNT(*) AS n FROM clients WHERE tenant_id='default'"),
    count(db, "SELECT COUNT(*) AS n FROM requests WHERE tenant_id='default'"),
    count(db, "SELECT COUNT(*) AS n FROM media WHERE tenant_id='default'"),
  ]);
  const card = (x, y, label, value) => `<rect x="${x}" y="${y}" width="165" height="86" rx="16" fill="${dark ? '#1c2030' : '#ffffff'}" stroke="${dark ? '#2b3147' : '#e3e6f0'}"/><text x="${x + 16}" y="${y + 36}" font-size="28" font-weight="700" fill="${fg}">${esc(value)}</text><text x="${x + 16}" y="${y + 62}" font-size="14" fill="${muted}">${esc(label)}</text>`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="390" height="520" viewBox="0 0 390 520" font-family="system-ui,-apple-system,Segoe UI,Roboto,sans-serif">
<rect width="390" height="520" fill="${bg}"/>
<rect width="390" height="120" fill="${accent}"/>
<text x="24" y="62" font-size="30" font-weight="700" fill="#ffffff">${name}</text>
<text x="24" y="90" font-size="14" fill="#ffffffcc">Snapshot of the app data · v${esc(version)}</text>
${card(24, 148, 'tools', tools)}${card(201, 148, 'styles', styles)}${card(24, 252, 'clients', clients)}${card(201, 252, 'requests', requests)}${card(24, 356, 'media files', media)}
<rect x="201" y="356" width="165" height="86" rx="16" fill="${accent}" opacity="0.14"/><text x="217" y="392" font-size="16" font-weight="700" fill="${accent}">${esc(String(kind || 'all').toUpperCase())}</text><text x="217" y="418" font-size="14" fill="${muted}">${esc(new Date(at).toISOString().slice(0, 16).replace('T', ' '))} UTC</text>
<text x="24" y="488" font-size="13" fill="${muted}">Generated by the server (no screenshot was available)</text>
</svg>`;
  return { buffer: Buffer.from(svg), type: 'image/svg+xml', source: 'generated' };
}

module.exports = { buildPreview, imageType };
